import random

# تولید یک عدد تصادفی بین ۱ تا ۱۰۰
عدد_مخفی = random.randint(1, 100)

# تعداد تلاش‌های مجاز
حداکثر_تلاش = 10
تلاش = 0
برنده = False

print("🎯 بازی حدس عدد شروع شد!")
print(f"یک عدد بین ۱ تا ۱۰۰ در نظر گرفته شده است.")
print(f"شما فقط {حداکثر_تلاش} تلاش دارید.\n")

while تلاش < حداکثر_تلاش:
    تلاش += 1
    print(f"تلاش شماره {تلاش}:")
    
    try:
        حدس = int(input("عدد حدس‌زده‌شده را وارد کنید: "))
    except ValueError:
        print("❌ لطفاً یک عدد صحیح وارد کنید!\n")
        تلاش -= 1  # این تلاش حساب نشود
        continue
    
    if حدس == عدد_مخفی:
        print(f"\n🎉 تبریک! شما برنده شدید.")
        print(f"عدد مخفی {عدد_مخفی} بود و شما در تلاش {تلاش} آن را پیدا کردید.")
        برنده = True
        break
    elif حدس < عدد_مخفی:
        print("⬆️ عدد شما کوچک‌تر از عدد مخفی است. بالاتر بروید.\n")
    else:
        print("⬇️ عدد شما بزرگ‌تر از عدد مخفی است. پایین‌تر بیایید.\n")

# بررسی باخت
if not برنده:
    print(f"\n😢 متأسفانه شما باختید!")
    print(f"عدد مخفی {عدد_مخفی} بود و شما در {حداکثر_تلاش} تلاش آن را پیدا نکردید.")